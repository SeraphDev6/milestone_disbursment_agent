/**
 * Generates src/design/themes.css from src/design/palette.ts and checks every declared pair's WCAG contrast.
 *   tsx scripts/tokens.ts           write themes.css, then check (exit 1 on any failure)
 *   tsx scripts/tokens.ts --check   check only, and fail if themes.css is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { formatHex, parse, wcagContrast } from "culori";
import { minimum, PAIRS, PALETTE, THEMES, type Theme, type ThemeColors } from "../src/design/palette.ts";

const OUT = fileURLToPath(new URL("../src/design/themes.css", import.meta.url));

function hex(c: string): string {
  const parsed = parse(c);
  if (!parsed) throw new Error(`can't parse colour ${c}`);
  return formatHex(parsed); // gamut-clipped sRGB, which is what the browser shows
}

function block(theme: Theme): string {
  const colors = PALETTE[theme] as ThemeColors;
  return Object.entries(colors)
    .map(([name, value]) => `  --${name}: ${hex(value)}; /* ${value} */`)
    .join("\n");
}

function css(): string {
  const scheme = { paper: "light", carbon: "dark", contrast: "light" } as const;
  const themed = THEMES.map(
    (t) => `:root[data-theme="${t}"] {\n  color-scheme: ${scheme[t]};\n${block(t)}\n}`,
  ).join("\n\n");
  return `/* Generated by scripts/tokens.ts from src/design/palette.ts. Do not edit by hand. */

/* Default: follow the OS until the person picks a theme (data-theme is then set on <html>). */
:root:not([data-theme]) {
  color-scheme: light;
${block("paper")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${block("carbon").replace(/^/gm, "  ")}
  }
}
@media (prefers-contrast: more) {
  :root:not([data-theme]) {
    color-scheme: light;
${block("contrast").replace(/^/gm, "  ")}
  }
}

${themed}
`;
}

function check(): number {
  let failures = 0;
  const rows: string[] = [];
  for (const theme of THEMES) {
    const colors = PALETTE[theme] as ThemeColors;
    for (const p of PAIRS) {
      const ratio = wcagContrast(hex(colors[p.fg]), hex(colors[p.bg]));
      const min = minimum(p.kind, theme);
      if (ratio < min) {
        failures++;
        rows.push(`  FAIL ${theme.padEnd(8)} ${p.fg} on ${p.bg}: ${ratio.toFixed(2)} < ${min} (${p.why})`);
      }
    }
  }
  const total = THEMES.length * PAIRS.length;
  if (failures) console.error(rows.join("\n"));
  console.log(`${total - failures}/${total} colour pairs meet their WCAG minimum across ${THEMES.length} themes.`);
  return failures;
}

const checkOnly = process.argv.includes("--check");
const generated = css();
if (checkOnly) {
  const current = readFileSync(OUT, "utf8");
  if (current !== generated) {
    console.error("themes.css is out of date with palette.ts; run `npm run tokens`.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, generated);
}
process.exit(check() ? 1 : 0);
