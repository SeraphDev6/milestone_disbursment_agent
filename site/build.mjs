#!/usr/bin/env node
/**
 * Builds the marketing site into _site/ (or the directory given as the first argument).
 *
 * No dependencies. It wraps each page in site/pages/ with site/layout.html, copies the static files, and takes
 * the colour tokens and the fonts from the web app so the site and the app can never drift apart:
 *   - web/src/design/themes.css (generated from palette.ts; every pair contrast-checked in CI)
 *   - web/src/design/tokens.css
 *   - the woff2 files of the three self-hosted families from web/node_modules/@fontsource (run `npm ci` in web/ first)
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const web = join(root, "web");
const out = process.argv[2] ? resolve(process.argv[2]) : join(root, "_site");

const NAV = [
  { href: "./", label: "Home", pages: ["index"] },
  { href: "./#how-it-works", label: "How it works", pages: [] },
  { href: "./security.html", label: "Security", pages: ["security"] },
  { href: "./accessibility.html", label: "Accessibility", pages: ["accessibility"] },
  { href: "https://github.com/SeraphDev6/milestone_disbursment_agent", label: "Source", pages: [], external: true },
];

// family, fontsource package, file stem, weight, style
const FONTS = [
  ["Newsreader", "newsreader", "newsreader-latin-400-normal", 400, "normal"],
  ["Newsreader", "newsreader", "newsreader-latin-600-normal", 600, "normal"],
  ["Newsreader", "newsreader", "newsreader-latin-400-italic", 400, "italic"],
  ["Atkinson Hyperlegible Next", "atkinson-hyperlegible-next", "atkinson-hyperlegible-next-latin-400-normal", 400, "normal"],
  ["Atkinson Hyperlegible Next", "atkinson-hyperlegible-next", "atkinson-hyperlegible-next-latin-400-italic", 400, "italic"],
  ["Atkinson Hyperlegible Next", "atkinson-hyperlegible-next", "atkinson-hyperlegible-next-latin-600-normal", 600, "normal"],
  ["Atkinson Hyperlegible Next", "atkinson-hyperlegible-next", "atkinson-hyperlegible-next-latin-700-normal", 700, "normal"],
  ["Atkinson Hyperlegible Mono", "atkinson-hyperlegible-mono", "atkinson-hyperlegible-mono-latin-400-normal", 400, "normal"],
  ["Atkinson Hyperlegible Mono", "atkinson-hyperlegible-mono", "atkinson-hyperlegible-mono-latin-600-normal", 600, "normal"],
];

function fail(msg) {
  console.error(`site/build.mjs: ${msg}`);
  process.exit(1);
}

function frontMatter(html) {
  const m = html.match(/^\s*<!--([\s\S]*?)-->/);
  if (!m) fail("a page must start with a <!-- title: ... --> comment");
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^\s*(\w+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].trim();
  }
  return { meta, body: html.slice(m[0].length).trim() };
}

function escapeAttr(s) {
  return s.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
}

function nav(page) {
  return NAV.map((item) => {
    const current = item.pages.includes(page) ? ' aria-current="page"' : "";
    const ext = item.external ? ' rel="noopener"' : "";
    return `<a class="nav-link" href="${item.href}"${current}${ext}>${item.label}</a>`;
  }).join("\n        ");
}

// 1. Clean output.
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "css"), { recursive: true });
mkdirSync(join(out, "fonts"), { recursive: true });

// 2. Tokens and themes from the app (single source of truth for colour).
for (const f of ["themes.css", "tokens.css"]) {
  const src = join(web, "src", "design", f);
  if (!existsSync(src)) fail(`${src} is missing`);
  cpSync(src, join(out, "css", f));
}

// 3. Fonts from the app's installed packages; the site's own fonts.css points at the copies.
const faces = [];
for (const [family, pkg, stem, weight, style] of FONTS) {
  const src = join(web, "node_modules", "@fontsource", pkg, "files", `${stem}.woff2`);
  if (!existsSync(src)) fail(`${src} is missing: run \`npm ci\` in web/ first`);
  cpSync(src, join(out, "fonts", `${stem}.woff2`));
  faces.push(
    `@font-face {\n  font-family: "${family}";\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url(../fonts/${stem}.woff2) format("woff2");\n}`,
  );
}
writeFileSync(join(out, "css", "fonts.css"), `/* Generated by site/build.mjs from web/node_modules/@fontsource. SIL Open Font License 1.1. */\n${faces.join("\n")}\n`);

// 4. The site's own files.
cpSync(join(here, "css", "site.css"), join(out, "css", "site.css"));
cpSync(join(here, "js"), join(out, "js"), { recursive: true });
cpSync(join(here, "static"), out, { recursive: true });
cpSync(join(web, "public", "favicon.svg"), join(out, "favicon.svg"));

// 5. Pages.
const layout = readFileSync(join(here, "layout.html"), "utf8");
const pages = readdirSync(join(here, "pages")).filter((f) => f.endsWith(".html"));
for (const file of pages) {
  const page = file.replace(/\.html$/, "");
  const { meta, body } = frontMatter(readFileSync(join(here, "pages", file), "utf8"));
  if (!meta.title || !meta.description) fail(`${file}: title and description are required`);
  const title = page === "index" ? `Milestone Ledger · ${meta.title}` : `${meta.title} · Milestone Ledger`;
  const html = layout
    .replaceAll("{{title}}", escapeAttr(title))
    .replaceAll("{{description}}", escapeAttr(meta.description))
    .replaceAll("{{page}}", page)
    .replace("{{nav}}", nav(page))
    .replace("{{content}}", body);
  writeFileSync(join(out, file), html);
}

console.log(`site: ${pages.length} pages, ${FONTS.length} fonts -> ${out}`);
